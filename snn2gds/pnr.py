"""Run OpenROAD-flow-scripts (ASAP7) on a generated design and collect area/timing/power.

ORFS is NOT vendored: point ORFS_HOME at a built checkout
(default: ~/OpenROAD-flow-scripts, or third_party/OpenROAD-flow-scripts if that submodule exists).
All ORFS outputs go to runs/<name>/orfs/work (WORK_HOME), not into the ORFS tree.
"""
from __future__ import annotations

import json
import os
import re
import subprocess
from pathlib import Path

from .config import Config

REPO = Path(__file__).resolve().parent.parent
PLATFORM = "asap7"


def orfs_home() -> Path:
    cands = [os.environ.get("ORFS_HOME"), REPO / "third_party" / "OpenROAD-flow-scripts",
             Path.home() / "OpenROAD-flow-scripts"]
    for c in cands:
        if c and (Path(c) / "flow" / "Makefile").exists():
            return Path(c).resolve()
    raise FileNotFoundError("OpenROAD-flow-scripts not found; set ORFS_HOME (see README)")


def _write_if_changed(path: Path, text: str):
    """Keep timestamps (and thus ORFS make state) when nothing changed, so reruns resume."""
    if not path.exists() or path.read_text() != text:
        path.write_text(text)


def write_design(cfg: Config) -> Path:
    out = cfg.run_dir.resolve()
    rtl = out / "rtl"
    d = out / "orfs"
    d.mkdir(parents=True, exist_ok=True)
    srcs = sorted(p for p in rtl.glob("*.v") if p.name != "tb.v")
    hw = cfg.hw
    _write_if_changed(d / "constraint.sdc", f"""current_design snn_top
set clk_period {hw.clk_period_ps}
create_clock -name core_clock -period $clk_period [get_ports clk]
set_input_delay  [expr $clk_period * 0.2] -clock core_clock [delete_from_list [all_inputs] [get_ports clk]]
set_output_delay [expr $clk_period * 0.2] -clock core_clock [all_outputs]
""")
    _write_if_changed(d / "config.mk", f"""# generated by snn2gds
export PLATFORM         = {PLATFORM}
export DESIGN_NAME      = snn_top
export DESIGN_NICKNAME  = {cfg.name}
export VERILOG_FILES    = {' '.join(str(s) for s in srcs)}
export SDC_FILE         = {d / 'constraint.sdc'}
export CORE_UTILIZATION = {hw.core_utilization}
export PLACE_DENSITY    = {hw.place_density}
export SKIP_LAST_GASP  ?= 1
""")
    return d


def run(cfg: Config, target: str = "finish", jobs: int | None = None) -> dict:
    """target: 'synth' (cell area only), 'grt' (stop after global route; area/timing estimates,
    skips the memory-hungry detailed router) or 'finish' (full place & route)."""
    d = write_design(cfg)
    orfs = orfs_home()
    work = d / "work"
    env = dict(os.environ)
    env["PATH"] = f"{orfs}/tools/install/OpenROAD/bin:{orfs}/tools/install/yosys/bin:{env['PATH']}"
    env["FLOW_HOME"] = str(orfs / "flow")
    cmd = ["make", "-C", str(orfs / "flow"), f"DESIGN_CONFIG={d / 'config.mk'}",
           f"WORK_HOME={work}", f"NUM_CORES={jobs or cfg.hw.num_cores}", target]
    print(" ".join(cmd), flush=True)
    log = d / f"make_{target}.log"
    with open(log, "w") as fh:
        rc = subprocess.call(cmd, env=env, stdout=fh, stderr=subprocess.STDOUT)
    if rc != 0:
        raise RuntimeError(f"ORFS {target} failed (rc={rc}); see {log}")
    m = collect(cfg)
    (cfg.run_dir / f"metrics_pnr_{target}.json").write_text(json.dumps(m, indent=1))
    print(json.dumps(m, indent=1))
    return m


def collect(cfg: Config) -> dict:
    work = cfg.run_dir.resolve() / "orfs" / "work"
    rep = work / "reports" / PLATFORM / cfg.name / "base"
    logs = work / "logs" / PLATFORM / cfg.name / "base"
    m: dict = {}
    stat = rep / "synth_stat.txt"
    if stat.exists():
        hit = re.findall(r"Chip area for (?:top )?module.*?:\s*([\d.]+)", stat.read_text())
        if hit:
            m["synth_area_um2"] = float(hit[-1])
        cells = re.findall(r"^\s+(\d+)\s+\S+\s+cells\s*$|^\s+Number of cells:\s+(\d+)", stat.read_text(), re.M)
        if cells:
            m["synth_cells"] = int(next(x for x in cells[0] if x))
    grt = logs / "5_1_grt.json"
    if grt.exists():
        d = json.loads(grt.read_text())
        for k, v in {"globalroute__design__instance__area__stdcell": "grt_stdcell_area_um2",
                     "globalroute__design__core__area": "grt_core_area_um2",
                     "globalroute__design__instance__utilization": "grt_utilization",
                     "globalroute__global_route__wirelength": "grt_wirelength_um",
                     "globalroute__timing__setup__ws": "grt_setup_ws_ps",
                     "globalroute__power__total": "grt_power_w"}.items():
            if k in d:
                m[v] = d[k]
    fin = logs / "6_report.json"
    if fin.exists():
        d = json.loads(fin.read_text())
        keys = {"finish__design__instance__area__stdcell": "stdcell_area_um2",
                "finish__design__core__area": "core_area_um2",
                "finish__design__die__area": "die_area_um2",
                "finish__design__instance__utilization": "utilization",
                "finish__power__total": "power_w",
                "finish__timing__setup__ws": "setup_ws_ps"}
        for k, v in keys.items():
            if k in d:
                m[v] = d[k]
    m["clk_period_ps"] = cfg.hw.clk_period_ps
    return m
